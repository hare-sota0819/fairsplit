export const PAY_VERBS_KO: readonly string[] = PAY_VERB_ENTRIES.map((e) => e.stem)

/**
 * The 하-family verbalizers — the ONLY continuations that turn a verbal noun
 * into a verb: 계산했어/계산해/계산하고/계산한/계산할/계산함.
 *
 * This is the whitelist backlog #2 asks for, and it is a whitelist rather
 * than a 서/기 denylist on purpose: a noun-forming suffix inventory is open
 * (계산서/계산기/계산대/계산법/계산상/계산적…), while the verbalizer set is
 * closed at seven syllables.
 */
const VERBALIZER = ['하', '해', '했', '한', '할', '함', '합'] as const

/**
 * Endings that may follow an ALREADY-inflected pay-verb form. Each entry is
 * the ending's first syllable, so it covers everything built on it (`었` →
 * 었어/었다/었는데, `는` → 는데/는지, `게` → 게/게요).
 *
 * `으`/`을` carry the 으-mediated endings and the future attributive that the
 * regex this replaces also matched: 냈으니까/냈으면/냈으며, 냈을 때/냈을걸/
 * 사줬으면. They are safe to admit here because a VERBAL NOUN never consults
 * this list — it is held to `PAY_VERBALIZER` alone — so 계산서 cannot come
 * back in through 계산+을/으 or anything else.
 *
 * `서` is deliberately absent: no pay form needs a BARE 서 (the -아서/-어서
 * connective always shows its vowel first — 계산해서, 내서), and admitting it
 * would re-open 계산서 through the back door.
 */
const VERB_ENDING = [
  '어',
  '었',
  '아',
  '았',
  '으',
  '을',
  '다',
  '고',
  '는',
  '지',
  '네',
  '니',
  '나',
  '자',
  '요',
  '죠',
  '음',
  '게',
  '래',
  '겠',
  '더',
  '대',
  '거',
  '구',
  '잖',
  '습',
] as const

function anchoredAlternation(words: readonly string[]): RegExp {
  return new RegExp(`^(?:${words.join('|')})`)
}

/** Anchored: the text right after a VERBAL-NOUN pay stem must match this. */
export const PAY_VERBALIZER: RegExp = anchoredAlternation(VERBALIZER)

/** Anchored: the text right after an inflected pay-verb stem must match this. */
export const PAY_VERB_ENDING: RegExp = anchoredAlternation(VERB_ENDING)

const VERB_ENDING_SET: ReadonlySet<string> = new Set(VERB_ENDING)

/**
 * Continuations that make a BARE `ambiguous` stem an ordinary word rather than
 * a payment. Every one of them is a real Korean word starting with 내:
 *
 *   내게 (to me)      내음 (a scent)     내구 (durability)   내거 (mine)
 *   내습 (an assault) 내대 (a stand)     내나 / 내래 / 내아 / 내을 / 내어
 *   내지 / 내네
 *
 * This is a CLOSED set, swept rather than guessed: every pure-hangul surface
 * in mecab-ko-dic's NNG/MAG/NNP/VV/VA/IC/MM seed files (229,923 words) was
 * tested for "내 + a continuation that is entirely verb-ending material", and
 * these are the collisions that occur with 내 at the START of the word. The
 * collisions that occur INSIDE a longer word (안내자, 안내대, 끝내어, 끝내지,
 * 티내네, 제내지, 방송내보내다니) are not on this list because a continuation
 * cannot separate them — 내자 "let's pay" and 안내자 "a guide" have the SAME
 * continuation — so they are handled by the position rule instead: an
 * `ambiguous` stem only matches at the START of a token (parsers/split.ts).
 *
 * Everything else that is ending material still fires, which is the point of
 * the inversion: 내겠어 / 내겠다 / 내죠 / 내잖아 / 내고 / 내자 / 내는 / 내요 /
 * 내다 / 내다니 are all payments and all resolve their payer.
 */
const AMBIGUOUS_STEM_COLLISION_WORDS: readonly string[] = [
  '어', '게', '음', '구', '거', '습', '대', '나', '래', '아', '을', '지', '네',
]

/**
 * The collisions above, each ALSO with every particle that can ride on it.
 *
 * Every collision is a NOUN (내게 "to me", 내음 "a scent", 내거 "mine"), and a
 * noun takes josa — so 내게는 / 내거는 / 내구는 / 내게나 are the same words
 * wearing a particle, and exact-matching the bare form let all of them through
 * as pay verbs (fix round 3). A VERB ENDING is not a josa, which is exactly
 * why this is generated from `JOSA` rather than done as a prefix match: 내네요
 * and 내지요 START with a collision (네, 지) and are ordinary polite verb
 * forms, so a prefix rule would silence them too.
 *
 * The product is small by construction: `isAmbiguousStemEnding` has already
 * required the whole continuation to be verb-ending material, and only 나 / 는
 * / 을 of the mined 43-josa inventory are made of ending syllables — every
 * other particle (이/가/도/만/에/를/…) is refused one step earlier.
 */
const AMBIGUOUS_STEM_COLLISIONS: ReadonlySet<string> = new Set([
  ...AMBIGUOUS_STEM_COLLISION_WORDS,
  ...AMBIGUOUS_STEM_COLLISION_WORDS.flatMap((word) => JOSA.map((josa) => word + josa)),
])

/**
 * Whether `rest` is a legal continuation for a BARE `ambiguous` stem: entirely
 * verb-ending material (which is what keeps 내지갑 / 내구성 out — 갑 and 성
 * are not endings), and not one of the swept collisions above.
 */
export function isAmbiguousStemEnding(rest: string): boolean {
  if (rest === '') return false
  if (AMBIGUOUS_STEM_COLLISIONS.has(rest)) return false
  return [...rest].every((syllable) => VERB_ENDING_SET.has(syllable))
}

/**
 * The verbalizing-suffix whitelist of the brief: a pay stem counts only when
 * what follows it is one of these, or nothing at all (end of the word).
 *
 * It is the UNION of the two class-specific whitelists above; matching it is
 * necessary for every stem, and SUFFICIENT only for the `verb-form` class —
 * a `verbal-noun` stem is additionally held to `PAY_VERBALIZER`, which is
 * what keeps 계산서/계산기 from firing (backlog #2). `findPayVerbs`
 * (parsers/split.ts) applies exactly that rule.
 */
export const PAY_VERB_SUFFIX: RegExp = anchoredAlternation([...VERBALIZER, ...VERB_ENDING])

// --- split expressions ------------------------------------------------------

/**
 * Korean split vocabulary. Matched against the RAW INPUT (not per token), so
 * a spaced variant is its own entry ("다 같이") rather than a whitespace
 * pattern — an entry is exactly the text it matches, which is what lets every
 * hit carry an exact span (backlog #5: only spans an actual hit consumed are
 * ever removed from the description; there is no global NOISE sweep).
 *
 * Hangul has no \b, so these fire on substrings in principle. 엔빵/다같이/
 * 모두/전부/나눠/나누자/반반/절반 are specific enough that a false hit inside
 * another word is not a realistic concern — the same judgement index.ts's
 * EVERYONE regex has always made, deliberately preserved here.
 *
 * Deliberately NOT included: bare 같이 (product ruling, coordinator
 * 2026-08-09). It adds nothing when no member is named — participants already
 * default to everyone in that case — and it actively misreads a restriction
 * when a member IS named: "민수랑 같이 저녁 3만원" means "with Minsu" (a
 * two-person split), not "with Minsu, everyone". A standalone "다같이" still
 * means everyone and is unaffected.
 */
