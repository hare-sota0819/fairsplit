/**
 * Curated Korean verb / split lexicons.
 *
 * STEMS ONLY. Not one inflected form is written down here: 냈어/냈다/냈고/
 * 냈는데 are the stem 냈 plus `PAY_VERB_ENDING`, and 고른/먹은/만든 are a stem
 * from `VERB_STEMS_KO` plus the attributive grammar in ko/attributive.ts.
 * Enumerating the product of a lexicon and a grammar is precisely the failure
 * this branch has logged over and over (docs/SOLVED.md [2026-08-13]).
 *
 * CURATION vs MINING: the sibling `lexicon-josa`/`lexicon-decoys`/
 * `lexicon-typos` modules are GENERATED by
 * scripts/lang/mine-korean-lexicons.mjs (mecab-ko-dic + open-korean-text).
 * The tables below are hand-curated instead — mecab-ko-dic's VV.csv (동사) and
 * VA.csv (형용사) are the natural sources for `VERB_STEMS_KO` /
 * `ADJ_STEMS_KO`, but mining needs network access, which was not available in
 * the session that wrote this file. The shape is deliberately mining-ready:
 * these arrays are plain stem lists with no grammar baked in, so a future
 * `mineVerbs`/`mineAdjectives` pass can replace their CONTENTS without any
 * change to ko/attributive.ts. Scope is this product's domain (expense chat),
 * which is also why a full dictionary would need filtering, not just import.
 */

// --- pay verbs --------------------------------------------------------------

export interface PayVerbEntry {
  /** Surface stem, matched as a prefix INSIDE a hangul token. */
  stem: string
  /**
   * `verbal-noun` — a noun that is only a verb once a 하-suffix verbalizes it
   * (계산 → 계산했어). Backlog #2 lives here: a verbal noun followed by a
   * NOUN-forming suffix is still a noun, so 계산서 (the bill) and 계산기 (a
   * calculator) must never fire as pay-verbs.
   *
   * `verb-form` — already a verb: either an inflected form (냈, 샀, 긁었) or a
   * vowel-final stem that takes endings directly (쏘 → 쏠게/쏜다).
   *
   * NOT covered by either class: the PASSIVE 되-family (계산됐어, 결제됨,
   * 정산돼) — 됐/됨/돼 is neither a 하-verbalizer nor an ending, so those
   * sentences report no pay verb today. They are a real (if less common)
   * expense-chat shape; the fix is a 되-family entry alongside
   * `PAY_VERBALIZER`, deliberately deferred rather than smuggled into the
   * verbalizer list, where it would also accept 계산되기/계산될 nouns.
   */
  kind: 'verbal-noun' | 'verb-form'
  /**
   * The BARE form of this stem is a common word in its own right, so it is
   * held to two extra conditions: it must sit at the START of its token, and
   * its continuation must not be one of the swept collisions
   * (`AMBIGUOUS_STEM_COLLISIONS`). Its FUSED forms are unaffected.
   *
   * 내 is the case this exists for, and it collides three ways: on its own it
   * is the possessive "my" (내 잔액 / 내 지갑 / 내 몫); in the space-stripped
   * shadow text this parser also reads it starts ordinary nouns (내지갑 = 내 +
   * 지 + 갑, 내구성 = 내 + 구 + 성); and it is the tail of a family of
   * everyday verbs whose endings are real verb endings (끝내지, 티내네, 내게,
   * 방송내보내다니). Nothing about the SHAPE of those continuations separates
   * them from a payment — only the list does.
   *
   * Deliberately a per-entry FACT rather than a rule about stem length: 쏘 is
   * one syllable too and is not a word by itself, so it keeps the default.
   */
  ambiguous?: true
}

